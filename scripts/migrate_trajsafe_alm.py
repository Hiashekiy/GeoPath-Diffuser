"""Migrate TrajSafe-Diffuser's ALM closed loop VERBATIM into our vendor tree.

Copies, without touching any body line:
    references/TrajSafe-Diffuser/src/diffusion/alm_local.py     -> vendor/trajsafe/alm_local.py
    references/TrajSafe-Diffuser/src/geometry/ellipse_densify.py-> vendor/trajsafe/ellipse_densify.py

and extracts, verbatim from their sampler.py, the dense-validation helpers:
    _dense_decode, _free_mask, _point_constraint_table, _point_violation,
    _membership_rate, dense_validation              -> vendor/trajsafe/dense_validation.py

Only ``import`` lines are rewritten (module paths); the audit at the end proves it
by re-diffing the result against the reference and printing every changed line.
"""
from __future__ import annotations

import difflib
import os
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
REF = ROOT / "references" / "TrajSafe-Diffuser"
OUT = ROOT / "src" / "gp_diffuser" / "vendor" / "trajsafe"

REWRITES = {
    "alm_local.py": [
        ("from ..geometry.bspline_constraints import build_constraint_pack",
         "from ...safety.bspline_constraints import build_constraint_pack"),
        ("from ..geometry.convex_region import EllipseRegionBuilder",
         "from ...safety.convex_region import EllipseRegionBuilder"),
        ("from ..geometry.ellipse_densify import densify_ellipses",
         "from .ellipse_densify import densify_ellipses"),
        ("from ..geometry.safety_corridor import build_safety_corridor",
         "from ...safety.safety_corridor import build_safety_corridor"),
        ("from .bspline_alm import bspline_alm_correct",
         "from ...diffusion.bspline_alm import bspline_alm_correct"),
        ("from .sampler import dense_validation",
         "from .dense_validation import dense_validation"),
    ],
    "ellipse_densify.py": [
        ("from .safety_corridor import halfspaces_to_vertices, overlap_ratio",
         "from ...safety.safety_corridor import halfspaces_to_vertices, overlap_ratio"),
    ],
}

HEADER = '''# VERBATIM migration of ``{src}`` from references/TrajSafe-Diffuser.
# Only the ``import`` lines were rewritten (module paths); every other line is
# byte-identical to the reference file.  Regenerated by
# ``scripts/migrate_trajsafe_alm.py``; do not edit by hand -- re-run the migration.
'''


def _copy_with_rewrites(name: str, ref_rel: str) -> None:
    src = REF / ref_rel
    text = src.read_text(encoding="utf-8")
    body = text
    for old, new in REWRITES[name]:
        assert old in body, "expected import line missing in %s: %s" % (name, old)
        body = body.replace(old, new)
    # drop the reference module docstring's first line only if we prepend a header
    out = HEADER.format(src=ref_rel.replace("\\", "/")) + body
    (OUT / name).write_text(out, encoding="utf-8")
    diff = [l for l in difflib.unified_diff(text.splitlines(), body.splitlines(),
                                            lineterm="", n=0)
            if l[:1] in "+-" and l[:3] not in ("+++", "---")]
    print("%-20s %4d lines, %d import line(s) rewritten" %
          (name, len(text.splitlines()), len(diff)))
    for line in diff:
        print("    " + line)


def _extract_dense_validation() -> None:
    sampler = REF / "src" / "diffusion" / "sampler.py"
    lines = sampler.read_text(encoding="utf-8").splitlines()
    keep_ranges = [(294, 298), (346, 352), (354, 385), (387, 417)]
    chunks = []
    for a, b in keep_ranges:
        chunks.append("\n".join(lines[a - 1:b]))
    body = ("from __future__ import annotations\n\n"
            "import torch\nimport torch.nn.functional as F\n\n"
            '__all__ = ["dense_validation"]\n\n\n'
            + "\n\n\n".join(chunks) + "\n")
    (OUT / "dense_validation.py").write_text(
        HEADER.format(src="src/diffusion/sampler.py (lines 294-417, verbatim)") + body,
        encoding="utf-8")
    print("dense_validation.py    extracted %d line ranges verbatim" % len(keep_ranges))


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    _copy_with_rewrites("alm_local.py", "src/diffusion/alm_local.py")
    _copy_with_rewrites("ellipse_densify.py", "src/geometry/ellipse_densify.py")
    _extract_dense_validation()
    (OUT / "__init__.py").write_text(
        '"""Vendored TrajSafe-Diffuser ALM closed loop (verbatim, imports only)."""\n\n'
        'from .alm_local import alm_closed_loop, collision_intervals, collision_mask\n'
        'from .dense_validation import dense_validation\n'
        'from .ellipse_densify import densify_ellipses\n\n'
        '__all__ = ["alm_closed_loop", "collision_intervals", "collision_mask",\n'
        '           "dense_validation", "densify_ellipses"]\n',
        encoding="utf-8")
    print("written:", OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
